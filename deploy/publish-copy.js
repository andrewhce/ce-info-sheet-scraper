'use strict';
// Publishes the read-only copy through GitHub. It builds the copy into a separate git repository,
// commits and pushes. Cloudflare Pages, connected to that repository, then deploys it.
//
//   node deploy/publish-copy.js --setup                 once: make the repository folder with a placeholder page
//   node deploy/publish-copy.js --url https://x.pages.dev     first publish (the address is remembered)
//   node deploy/publish-copy.js                          later publishes
//   node deploy/publish-copy.js --dry-run                check only: builds, commits and pushes nothing
//
// Options:
//   --repo PATH     the repository folder (default: a folder called school-info-site next to this project)
//   --url ADDRESS   the Cloudflare Pages address of the project
//   --no-sheet      leave out the workbook's school-tab text (then no login check is needed)
//
// Safety: the copy contains the workbook's school-tab text, and a push publishes it. The script will not
// build or push until the Pages address answers with a Cloudflare Access login redirect.
const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const { PATHS, readJson, writeJson } = require('../src/lib/util');
const { guarded } = require('../src/lib/access-check');

const args = process.argv.slice(2);
const opt = (k) => { const i = args.indexOf(k); return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : null; };
const has = (k) => args.includes(k);
const STATE = path.join(PATHS.data, 'publish.json');
const saved = readJson(STATE, {});
const repo = path.resolve(PATHS.root, opt('--repo') || saved.repo || path.join('..', 'school-info-site'));
const noSheet = has('--no-sheet');
const dryRun = has('--dry-run');
const MARKER = '.school-info-site';

const git = (...a) => spawnSync('git', a, { cwd: repo, encoding: 'utf8' });
const fail = (msg, code = 1) => { console.error(msg); process.exit(code); };

function setup() {
  if (fs.existsSync(path.join(repo, '.git'))) { console.log(`${repo} is already a git repository. Nothing to do.`); return; }
  if (fs.existsSync(repo) && fs.readdirSync(repo).length) fail(`${repo} already has files in it. Choose another folder with --repo.`);
  fs.mkdirSync(path.join(repo, 'public'), { recursive: true });
  fs.writeFileSync(path.join(repo, 'README.md'), [
    '# School Info Sheet: published pages',
    '',
    'Generated by `node deploy/publish-copy.js` in the school-info-scraper project. Do not edit by hand: the next publish replaces `public/`.',
    'Cloudflare Pages serves the `public/` folder. Keep this repository **private**: unless it was built with `--no-sheet`,',
    'it holds text from the team\'s workbook.',
    '',
  ].join('\n'));
  fs.writeFileSync(path.join(repo, 'public', MARKER), 'Made by build-static.js. This folder is emptied and rebuilt each time.\n');
  fs.writeFileSync(path.join(repo, 'public', 'index.html'),
    '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="robots" content="noindex, nofollow"><title>Nothing published yet</title></head>' +
    '<body style="font-family:system-ui,sans-serif;margin:3rem"><p>Nothing has been published here yet.</p></body></html>\n');
  const steps = [['init', '-b', 'main'], ['add', '-A'], ['commit', '-m', 'Placeholder page']];
  for (const s of steps) {
    const r = git(...s);
    if (r.status !== 0) fail(`git ${s[0]} failed: ${(r.stderr || r.stdout || '').trim()}\n(If it says to tell git who you are: git config --global user.name "Your name"; git config --global user.email "you@example.com")`);
  }
  writeJson(STATE, { ...saved, repo });
  console.log(`Repository made at ${repo} (one placeholder page, nothing from your data).\n\nNext:\n` +
    '  1. On github.com make a new PRIVATE repository, empty (no README, no .gitignore). Copy its address.\n' +
    `  2. In ${repo}:   git remote add origin <that address>   then   git push -u origin main\n` +
    '  3. Connect that repository to a new Cloudflare Pages project and add the Access login (docs/DEPLOY-GUIDE.md, section 5b).\n' +
    '  4. Then publish: node deploy/publish-copy.js --url https://<your-project>.pages.dev/');
}

(async () => {
  if (has('--setup')) return setup();

  if (!fs.existsSync(path.join(repo, '.git'))) fail(`${repo} is not a git repository yet. Run:  node deploy/publish-copy.js --setup`);
  const remote = git('remote', 'get-url', 'origin');
  if (remote.status !== 0) fail(`The repository at ${repo} has no GitHub address yet. In that folder run:  git remote add origin <your private repository address>`);
  const branch = (git('rev-parse', '--abbrev-ref', 'HEAD').stdout || '').trim() || 'main';

  let home = opt('--url') || saved.url;
  if (!noSheet) {
    if (!home) fail('Give the Cloudflare Pages address once:  node deploy/publish-copy.js --url https://your-project.pages.dev/');
    if (!/^https?:\/\//i.test(home)) fail('--url must start with https://');
    if (!home.endsWith('/')) home += '/';
    const g = await guarded(home);
    if (!g.ok) {
      fail(`\nNot publishing. ${home} did not answer with a Cloudflare Access login (it said: ${g.seen}).\n` +
        'A push publishes the copy, and it contains the workbook\'s school-tab text, so the login must be in place first.\n' +
        'Set up Cloudflare Access for this address (docs/DEPLOY-GUIDE.md), then run this again.', 2);
    }
    console.log(`Login check passed: ${g.seen}.`);
  } else console.log('Login check skipped: this copy has no workbook text.');
  console.log(`Repository: ${repo}   branch: ${branch}   remote: ${(remote.stdout || '').trim()}`);
  if (dryRun) { console.log('Dry run: nothing was built, committed or pushed.'); return; }

  const out = path.join(repo, 'public');
  const b = spawnSync(process.execPath, [path.join('deploy', 'build-static.js'), '--out', out, ...(noSheet ? ['--no-sheet'] : [])], { cwd: PATHS.root, stdio: 'inherit' });
  if (b.status !== 0) fail('The export failed, so nothing was committed.');

  git('add', '-A');
  if (!(git('status', '--porcelain').stdout || '').trim()) { console.log('\nNothing new to publish.'); return; }
  const stamp = new Date().toISOString().slice(0, 10);
  const c = git('commit', '-m', `Update school results ${stamp}${noSheet ? ' (no workbook text)' : ''}`);
  if (c.status !== 0) fail(`git commit failed: ${(c.stderr || c.stdout || '').trim()}`);
  console.log('\nPushing to GitHub ...');
  const p = spawnSync('git', ['push', 'origin', branch], { cwd: repo, stdio: 'inherit' });
  if (p.status !== 0) fail('\nThe push did not go through, so nothing was published. The commit is saved in the repository; run this again after fixing the problem above.');
  writeJson(STATE, { repo, ...(home ? { url: home } : {}), lastPublishAt: new Date().toISOString() });
  console.log(`\nPushed. Cloudflare builds it in about a minute.${home ? ' Open ' + home : ''}`);
})().catch((e) => { console.error(e); process.exit(1); });
